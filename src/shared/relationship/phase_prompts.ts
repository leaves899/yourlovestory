/**
 * 获取阶段专属写作规则。
 *
 * @param phase - 关系阶段
 * @returns 写作规则
 */
export function getPhaseWritingRules(phase: RelationshipPhase): string {
  return PHASE_WRITING_RULES[phase] || ''
}

/**
 * 构建包含阶段规则的系统 Prompt。
 *
 * @param basePrompt - 基础 Prompt
 * @param phase - 关系阶段
 * @returns 包含阶段规则的系统 Prompt
 */
export function buildPhaseAwareSystemPrompt(
  basePrompt: string,
  phase: RelationshipPhase
): string {
  const phaseRules = getPhaseWritingRules(phase)

  if (!phaseRules) {
    return basePrompt
  }

  return `${basePrompt}\n\n---\n\n${phaseRules}`
}
